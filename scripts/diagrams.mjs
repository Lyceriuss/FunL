// Draws every Mermaid diagram in docs/ as an SVG image in docs/diagrams/ and
// collects them on one page, docs/DIAGRAMS.md (grouped by doc, with a contents
// list), plus the "How it fits together" section of README.md. Images show in
// any Markdown viewer (VS Code's plain preview, GitHub), no extension needed.
// The diagrams themselves stay in their source docs; edit them there.
//
//   npm run diagrams              regenerate (draws only new or changed diagrams)
//   npm run diagrams -- --force   redraw every image
//   npm run diagrams -- --check   exit 1 if anything is stale (npm test checks this too)
//
// Drawing needs Edge or Chrome installed (driven by playwright-core); the check doesn't.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const OUT = 'docs/DIAGRAMS.md';
export const IMAGES = 'docs/diagrams';
const README_START = '<!-- diagrams:start (generated by `npm run diagrams`, do not edit by hand) -->';
const README_END = '<!-- diagrams:end -->';
const BACKGROUND = '#0b0820';
const PAD = 16;

/** Mermaid blocks in one Markdown doc, each with the heading it sits under. */
export function diagramsIn(markdown, path) {
  const out = [];
  let heading = '';
  let block = null;
  for (const line of markdown.split(/\r?\n/)) {
    if (block) {
      if (line.trim() === '```') {
        const source = block.join('\n').trim();
        const n = out.filter((d) => d.heading === heading).length;
        out.push({ path, heading, title: n ? `${heading} (${n + 1})` : heading, kind: kindLabel(source.split(/\s/)[0] ?? ''), source });
        block = null;
      } else block.push(line);
      continue;
    }
    const h = line.match(/^#{2,3}\s+(.+?)\s*$/);
    if (h) heading = h[1];
    else if (line.trim() === '```mermaid') block = [];
  }
  return out;
}

/** Friendly name for a Mermaid diagram type. */
export function kindLabel(kind) {
  if (kind.startsWith('flowchart') || kind.startsWith('graph')) return 'Flow';
  if (kind.startsWith('classDiagram')) return 'Class (UML)';
  if (kind.startsWith('stateDiagram')) return 'State (UML)';
  if (kind.startsWith('sequenceDiagram')) return 'Sequence (UML)';
  if (kind.startsWith('erDiagram')) return 'Data (ER)';
  return kind || 'Diagram';
}

/** GitHub's heading anchor: lowercase, punctuation dropped, spaces → hyphens. */
export function slug(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s/g, '-');
}

function slugger() {
  const seen = new Map();
  return (heading) => {
    const base = slug(heading);
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    return n ? `${base}-${n}` : base;
  };
}

/** Short hash of a diagram's source, stamped into its SVG to spot stale images. */
export const sourceHash = (source) => createHash('sha256').update(source).digest('hex').slice(0, 16);
const stamp = (hash) => `<!-- funl-diagram ${hash} -->`;

/** docs/**.md (except the generated file), sorted, ARCHITECTURE first. */
function docFiles(root) {
  const walk = (dir) =>
    readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
      e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.md') ? [join(dir, e.name)] : [],
    );
  return walk(join(root, 'docs'))
    .map((f) => relative(root, f).replaceAll('\\', '/'))
    .filter((f) => f !== OUT)
    .sort((a, b) => (a === 'docs/ARCHITECTURE.md' ? -1 : b === 'docs/ARCHITECTURE.md' ? 1 : a.localeCompare(b)));
}

/** Every doc with diagrams: { path, title (its H1), diagrams }. Each diagram gets an anchor and an image path. */
export function collect(root = ROOT) {
  const anchor = slugger();
  anchor('Diagrams');
  anchor('Contents');
  const docs = docFiles(root)
    .map((path) => {
      const md = readFileSync(join(root, path), 'utf8');
      const title = (md.match(/^#\s+(.+?)\s*$/m)?.[1] ?? path).replace(/`/g, '');
      return { path, title, diagrams: diagramsIn(md, path) };
    })
    .filter((d) => d.diagrams.length);
  for (const doc of docs) {
    doc.anchor = anchor(doc.title);
    const docSlug = slug(doc.path.replace(/^docs\//, '').replace(/\.md$/, '').replace(/\//g, ' '));
    for (const d of doc.diagrams) {
      d.anchor = anchor(d.title);
      d.image = `${IMAGES}/${docSlug}--${slug(d.title)}.svg`;
      d.hash = sourceHash(d.source);
    }
  }
  return docs;
}

const fromDocs = (path) => path.replace(/^docs\//, '');
const plain = (title) => title.replace(/`/g, '');

export function buildDiagramsDoc(docs) {
  const total = docs.reduce((n, d) => n + d.diagrams.length, 0);
  const contents = [];
  const body = [];
  for (const doc of docs) {
    contents.push(`**[${doc.title}](#${doc.anchor})** · [${doc.path}](${fromDocs(doc.path)})`, '');
    body.push(`## ${doc.title}`, '', `From [${doc.path}](${fromDocs(doc.path)}).`, '');
    for (const d of doc.diagrams) {
      contents.push(`- [${d.title}](#${d.anchor}) · ${d.kind}`);
      body.push(
        `### ${d.title}`,
        '',
        `*${d.kind}* · source: [${d.path} › ${plain(d.heading)}](${fromDocs(d.path)}#${slug(d.heading)}) · [open image](${fromDocs(d.image)})`,
        '',
        `![${plain(d.title)}](${fromDocs(d.image)})`,
        '',
      );
    }
    contents.push('');
  }
  return [
    '# Diagrams',
    '',
    `All ${total} diagrams of FunL in one place: how the game is put together (UML class, sequence, state and ER diagrams) and how it plays (flows).`,
    '',
    '> Generated by `npm run diagrams`, which draws each Mermaid block in `docs/` as an image in `docs/diagrams/`. Edit a diagram in its source doc (linked under each one), then run `npm run diagrams`. `npm test` fails while anything here is stale.',
    '',
    '## Contents',
    '',
    ...contents,
    ...body,
  ].join('\n').trimEnd() + '\n';
}

/** README section: the "game at a glance" image plus the list of all diagrams. */
export function buildReadmeSection(docs) {
  const [glance] = docs[0].diagrams;
  const lines = [README_START, `### ${plain(glance.heading).replace(/^\d+\.\s*/, '')}`, '', `![${plain(glance.title)}](${glance.image})`, '', `**All diagrams** (drawn together in [${OUT}](${OUT})):`, ''];
  for (const doc of docs) lines.push(`- **${doc.title}**`, ...doc.diagrams.map((d) => `  - [${plain(d.title).replace(/^\d+\.\s*/, '')}](${OUT}#${d.anchor}) · ${d.kind}`));
  lines.push(README_END);
  return lines.join('\n');
}

export function withReadmeSection(readme, section) {
  const start = readme.indexOf(README_START);
  const end = readme.indexOf(README_END);
  if (start < 0 || end < start) throw new Error(`README.md needs the markers ${README_START} … ${README_END}`);
  return readme.slice(0, start) + section + readme.slice(end + README_END.length);
}

/** Expected contents of the generated Markdown files: { path: text }. */
export function generate(root = ROOT, docs = collect(root)) {
  const readme = readFileSync(join(root, 'README.md'), 'utf8');
  return { [OUT]: buildDiagramsDoc(docs), 'README.md': withReadmeSection(readme, buildReadmeSection(docs)) };
}

const read = (path) => {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
};

/** Diagrams whose image is missing or drawn from an older source. */
export function staleImages(root = ROOT, docs = collect(root)) {
  return docs.flatMap((doc) => doc.diagrams).filter((d) => !read(join(root, d.image))?.startsWith(stamp(d.hash)));
}

/** Image files no diagram uses any more. */
function orphanImages(root, docs) {
  const used = new Set(docs.flatMap((doc) => doc.diagrams.map((d) => d.image)));
  let files = [];
  try {
    files = readdirSync(join(root, IMAGES)).map((f) => `${IMAGES}/${f}`);
  } catch {
    /* no folder yet */
  }
  return files.filter((f) => !used.has(f));
}

/** Generated files that are missing or out of date. */
export function stale(root = ROOT) {
  const docs = collect(root);
  const md = Object.entries(generate(root, docs))
    .filter(([path, text]) => read(join(root, path)) !== text)
    .map(([path]) => path);
  return [...md, ...staleImages(root, docs).map((d) => d.image), ...orphanImages(root, docs)];
}

/** Mermaid's SVG → a standalone image: fixed size, padding, dark background, source stamp. */
function finishSvg(svg, hash) {
  const vb = svg.match(/viewBox="([-\d.e]+) ([-\d.e]+) ([-\d.e]+) ([-\d.e]+)"/);
  if (!vb) throw new Error('Mermaid SVG has no viewBox');
  const [x, y, w, h] = vb.slice(1).map(Number);
  const box = [x - PAD, y - PAD, w + 2 * PAD, h + 2 * PAD].map((n) => Math.round(n * 100) / 100);
  const open = svg.match(/<svg[^>]*>/)[0];
  const newOpen = open
    .replace(/\swidth="[^"]*"/, '')
    .replace(/\sheight="[^"]*"/, '')
    .replace(/\sstyle="[^"]*"/, '')
    .replace(/viewBox="[^"]*"/, `viewBox="${box.join(' ')}" width="${Math.ceil(box[2])}" height="${Math.ceil(box[3])}"`);
  const bg = `<rect x="${box[0]}" y="${box[1]}" width="${box[2]}" height="${box[3]}" rx="12" fill="${BACKGROUND}"/>`;
  return `${stamp(hash)}\n${svg.replace(open, newOpen + bg)}\n`;
}

/** Draws the given diagrams with Mermaid in headless Edge (or Chrome). */
async function draw(root, diagrams) {
  const { chromium } = await import('playwright-core');
  let browser;
  for (const channel of ['msedge', 'chrome']) {
    try {
      browser = await chromium.launch({ channel });
      break;
    } catch {
      /* try the next browser */
    }
  }
  if (!browser) throw new Error('Drawing diagrams needs Microsoft Edge or Google Chrome installed.');
  try {
    const page = await browser.newPage();
    await page.setContent(`<body style="background:${BACKGROUND}"></body>`);
    await page.addScriptTag({ path: join(root, 'node_modules/mermaid/dist/mermaid.min.js') });
    const results = await page.evaluate(
      async ({ list, background }) => {
        window.mermaid.initialize({
          startOnLoad: false,
          securityLevel: 'strict',
          theme: 'dark',
          fontFamily: 'Arial, Helvetica, sans-serif',
          // Plain SVG text instead of HTML labels, so the images look the same in every viewer.
          htmlLabels: false,
          flowchart: { htmlLabels: false, curve: 'basis' },
          themeVariables: { background, primaryColor: '#1e1b4b', primaryBorderColor: '#22d3ee', primaryTextColor: '#f8fafc', lineColor: '#a78bfa' },
        });
        const out = [];
        for (const d of list) {
          try {
            out.push({ svg: (await window.mermaid.render(d.id, d.source)).svg });
          } catch (e) {
            out.push({ error: String(e?.message ?? e) });
          }
        }
        return out;
      },
      { list: diagrams.map((d) => ({ id: `funl-${d.anchor}`, source: d.source })), background: BACKGROUND },
    );
    const failed = [];
    results.forEach((r, i) => {
      const d = diagrams[i];
      if (r.error) failed.push(`${d.path} › ${d.title}: ${r.error.split('\n')[0]}`);
      else writeFileSync(join(root, d.image), finishSvg(r.svg, d.hash));
    });
    return failed;
  } finally {
    await browser.close();
  }
}

async function main(args) {
  const docs = collect();
  if (args.includes('--check')) {
    const out = stale();
    if (out.length) {
      console.error(`Stale: ${out.join(', ')}. Run npm run diagrams.`);
      process.exit(1);
    }
    console.log('Diagrams up to date.');
    return;
  }
  mkdirSync(join(ROOT, IMAGES), { recursive: true });
  for (const f of orphanImages(ROOT, docs)) rmSync(join(ROOT, f));
  const todo = args.includes('--force') ? docs.flatMap((d) => d.diagrams) : staleImages(ROOT, docs);
  const failed = todo.length ? await draw(ROOT, todo) : [];
  for (const [path, text] of Object.entries(generate(ROOT, docs))) writeFileSync(join(ROOT, path), text);
  const total = docs.reduce((n, d) => n + d.diagrams.length, 0);
  console.log(`${total} diagrams: drew ${todo.length - failed.length}, ${total - todo.length} unchanged. Wrote ${OUT}, ${IMAGES}/ and the README section.`);
  if (failed.length) {
    console.error(`These diagrams don't parse (fix them in their source doc):\n- ${failed.join('\n- ')}`);
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main(process.argv.slice(2));
